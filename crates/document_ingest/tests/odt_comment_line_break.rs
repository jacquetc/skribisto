//! A line break inside a LibreOffice comment must arrive as a paragraph break.
//!
//! An editor writing a two-line note has two ways to do it, and ODF records them
//! differently: **Enter** starts a second `<text:p>`, **Shift+Enter** puts a
//! `<text:line-break/>` inside the first one. Both mean "two lines".
//!
//! The second used to collapse to a single space, so the same remark imported as one run-on
//! sentence — and imported *differently* depending on whether the editor had used
//! LibreOffice or Word, since the DOCX scanner has always split on `RunChild::Break`. That
//! asymmetry is the thing these tests exist to stop coming back.
//!
//! Written against **flat ODF** (`.fodt`), which the scanner accepts alongside `.odt`: the
//! whole document is one XML file, so a fixture can be a string literal here rather than a
//! binary blob regenerated by a script — and a reader can see exactly what is being scanned.

use document_ingest::scanner::SourceScanner;
use document_ingest::sources::odt::OdtScanner;

/// A flat-ODF document whose single paragraph carries one annotation, with `body` spliced in.
fn fodt_with_comment_body(body: &str) -> String {
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<office:document
  xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0"
  xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0"
  xmlns:dc="http://purl.org/dc/elements/1.1/"
  office:mimetype="application/vnd.oasis.opendocument.text">
  <office:body>
    <office:text>
      <text:p>The street was gone by morning.
        <office:annotation office:name="a1">
          <dc:creator>Editor</dc:creator>
          <dc:date>2026-01-02T03:04:05</dc:date>
          {body}
        </office:annotation>
      </text:p>
    </office:text>
  </office:body>
</office:document>"#
    )
}

fn scan_body(fodt: &str) -> String {
    let doc = OdtScanner
        .scan(fodt.as_bytes(), "note.fodt", "note.fodt")
        .expect("the fixture must scan");
    assert_eq!(
        doc.annotations.len(),
        1,
        "the fixture carries exactly one comment: {:?}",
        doc.annotations
    );
    doc.annotations[0].body.clone()
}

/// Shift+Enter — the case that regressed.
#[test]
fn a_line_break_inside_a_comment_becomes_a_paragraph_break() {
    let body = scan_body(&fodt_with_comment_body(
        "<text:p>Cut this paragraph?<text:line-break/>It repeats ch. 3.</text:p>",
    ));

    assert!(
        !body.contains("Cut this paragraph? It repeats ch. 3."),
        "the line break must not collapse into a space — the editor wrote two lines and \
         meant two. body = {body:?}"
    );
    assert_eq!(
        skrib_format::djot_plain_text(&body)
            .expect("the body is Djot")
            .0,
        "Cut this paragraph?\nIt repeats ch. 3.",
        "two paragraphs, joined by exactly one newline when read back. body = {body:?}"
    );
}

/// Enter — the case that always worked. Here so a future change cannot fix one shape by
/// breaking the other, and so the two are pinned as producing the *same* result.
#[test]
fn two_paragraphs_written_with_enter_still_arrive_as_two() {
    let body = scan_body(&fodt_with_comment_body(
        "<text:p>Cut this paragraph?</text:p><text:p>It repeats ch. 3.</text:p>",
    ));

    assert_eq!(
        skrib_format::djot_plain_text(&body)
            .expect("the body is Djot")
            .0,
        "Cut this paragraph?\nIt repeats ch. 3.",
        "body = {body:?}"
    );
}

/// A tab is *not* a paragraph break — a comment box has no tab stops to honour, so it stays
/// a space. Pinned separately because the two used to share one match arm, and the fix
/// split them.
#[test]
fn a_tab_inside_a_comment_stays_a_space() {
    let body = scan_body(&fodt_with_comment_body(
        "<text:p>Cut this?<text:tab/>It repeats.</text:p>",
    ));

    assert_eq!(
        skrib_format::djot_plain_text(&body)
            .expect("the body is Djot")
            .0,
        "Cut this? It repeats.",
        "body = {body:?}"
    );
}

/// Consecutive breaks must not manufacture empty paragraphs, which would reach the card as
/// stray blank lines.
#[test]
fn consecutive_line_breaks_do_not_make_empty_paragraphs() {
    let body = scan_body(&fodt_with_comment_body(
        "<text:p>First.<text:line-break/><text:line-break/>Second.</text:p>",
    ));

    assert_eq!(
        skrib_format::djot_plain_text(&body)
            .expect("the body is Djot")
            .0,
        "First.\nSecond.",
        "body = {body:?}"
    );
}
